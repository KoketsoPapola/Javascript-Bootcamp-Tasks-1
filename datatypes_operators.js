
// Numbers
let integer = 10;
let float = 5.5;

console.log(integer + float);
console.log(integer - float);
console.log(integer * float);
console.log(integer / float);
console.log(integer % 3);
console.log(integer ** 2);


// Boolean & Comparison
let x = 8;
let y = 12;

console.log(x > y);
console.log(x <= y);
console.log(x == y);
console.log(x != y);


// Logical Operators
let a = true;
let b = false;

console.log(a && b);
console.log(a || b);
console.log(!a);


// Assignment Operators
let p = 10;

p += 5;
console.log(p);

p -= 3;
console.log(p);

p *= 2;
console.log(p);

p /= 4;
